using MAXIMUS.Core.Libraries;
using System;
using System.Collections.Generic;
using System.Data;
using System.Data.SqlClient;
using System.Reflection;
using Workflow;

namespace PDMSWorkflow
{
    public class WFSendToNFOCUS : BaseWorkflowTask, IWorkflowTask
    {
        string nextStep = null;

        public WFSendToNFOCUS(int processID, int stepID)
            : base(processID, stepID)
        {
        }

        override public bool ProcessTask()
        {
            string logMsg = String.Format(Constants.LogString.MethodSignature, MethodBase.GetCurrentMethod().DeclaringType.Name, MethodBase.GetCurrentMethod().Name);
            Logging log = new Logging(LogThreadID, logMsg);

            bool toReturn = false;

            int regID;
            Process p = new Process(ProcessID);

            try
            {
                if (!int.TryParse(p.GetProcessParameter(Constants.ProcessParameter.RegistrationID), out regID))
                {
                    throw new Exception(string.Format(
                        Constants.LogString.WorkflowParameterNotNumeric,
                        Assembly.GetExecutingAssembly().GetName().Name,
                        Constants.ProcessParameter.RegistrationID,
                        GetProcessParameter(Constants.ProcessParameter.RegistrationID)));
                }

                // Insert Provider transaction
                int tqId = this.InsertTQRecord(regID, Constants.TransactionType.SendDIDDAddProviderUpdatetoMMIS);
                SetProcessParameter(Constants.ProcessParameter.TransactionQueueID, tqId.ToString());
                SaveProcessParameters();

                // Insert services transaction
                this.InsertTQRecord(regID, Constants.TransactionType.SendWaiverServicesUpdatetoMMIS);

                toReturn = true;
            }
            catch (Exception ex)
            {
                if (System.Diagnostics.Debugger.IsAttached) System.Diagnostics.Debugger.Break();
                throw CoreException.ThrowException(LogThreadID, ex, logMsg);
            }
            return toReturn;
        }
        override public string NextStep()
        {
            return nextStep;
        }

        private int InsertTQRecord(int regID, int transactionType)
        {
            // generated by sp_Admin_StoredProcBuilder on Aug 12 2013 12:11PM
            // create parameters objects and fill with values
            List<SqlParameter> parameters = new List<SqlParameter>();

            parameters.Add(SqlParms.CreateParameter("REG_ID", DbType.Int32, regID, true));
            parameters.Add(SqlParms.CreateParameter("TRANSACTION_TYPE_ID", DbType.Int32, transactionType, true));
            parameters.Add(SqlParms.CreateParameter("LAST_MODIFIED_DATE_TIME", DbType.DateTime, DateTime.Now, true));
            parameters.Add(SqlParms.CreateParameter("LAST_MODIFIED_USER", DbType.Guid, Constants.appWorkflowUserId, true));

            return Methods.GetIntValue(DataAccess.ExecuteScalar("usp_InsertDIDDMMISTransaction", parameters));
        }
    }
}
