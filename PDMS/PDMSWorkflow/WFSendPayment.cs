namespace PDMSWorkflow
{
    public class WFSendPayment : BaseWorkflowTask, IWorkflowTask
    {
        public WFSendPayment(int processID, int stepID)
            : base(processID, stepID)
        {
            //
            // TODO: Add constructor logic here
            //
        }

        override public bool ProcessTask()
        {
            string logMsg = String.Format(Constants.LogString.MethodSignature, MethodBase.GetCurrentMethod().DeclaringType.Name, MethodBase.GetCurrentMethod().Name);
            Logging log = new Logging(LogThreadID, logMsg);

            int changedPaymentInfo = 0;
            int rId;
            bool rIdParsed = false;
            int transactionType = 0;

            Process p = new Process(ProcessID);
            
            try
            {
                rIdParsed = int.TryParse(p.GetProcessParameter(Constants.ProcessParameter.RegistrationID), out rId);
                string partyID = GetProcessParameter(CON.ProcessParameter.PartyID);
                string serviceLocationID = GetProcessParameter(CON.ProcessParameter.ServiceLocationID);
                int pId = Convert.ToInt32(partyID);
                int sId = Convert.ToInt32(serviceLocationID);

                // if a service location id exists
                if (serviceLocationID.Length > 0)
                {
                    // generated by sp_Admin_StoredProcBuilder on Apr 14 2014 10:45AM
                    // create parameters objects and fill with values
                    List<SqlParameter> parameters = new List<SqlParameter>();

                    parameters.Add(SqlParms.CreateParameter("REG_ID", DbType.Int32, rId, true));

                    // verify if the payment information has changed
                    changedPaymentInfo = Methods.GetIntValue(DataAccess.ExecuteScalar("usp_CheckRegAccountingReview", parameters));
                }

                if (changedPaymentInfo == 2 || changedPaymentInfo == 3 || changedPaymentInfo == 4)
                {
                    TransactionController.InsertTransactionQueue((int)TransactionController.TransactionType.SendPaymentInfotoMMIS
                        , pId
                        , sId
                        , DateTime.Now
                        , null
                        , null
                        , DateTime.Now
                        , Constants.appWorkflowUserId);
                }
                else
                {
                    if (ChangedOrgType(rId))
                    {
                        string mId = SelectMedicaidId(sId);

                        if (mId.Length > 0)
                        {
                            transactionType = (int)TransactionController.TransactionType.SendProviderUpdatestoMMIS;
                        }
                        else
                        {
                            transactionType = (int)TransactionController.TransactionType.RequestMedicaidIDfromMMIS;
                        }

                        TransactionController.InsertTransactionQueue(
                            transactionType,
                            pId,
                            sId,
                            DateTime.Now,
                            null,
                            null,
                            DateTime.Now,
                            Constants.appWorkflowUserId);
                    }
                }

                // Finished with workflow, set TennCare status as Maintenance
                if (rIdParsed == false)
                {
                    throw new Exception(string.Format(
                        Constants.LogString.WorkflowParameterNotNumeric,
                        Assembly.GetExecutingAssembly().GetName().Name,
                        Constants.ProcessParameter.RegistrationID,
                        GetProcessParameter(Constants.ProcessParameter.RegistrationID)));
                }
                RegistrationController.SaveRegistrationProgramStatus(rId, Constants.RegistrationProgramStatusTypeId.Maintenance, DateTime.Now,
                    Constants.appAdminUserId);
                }
            catch (Exception ex)
            {
                throw CoreException.ThrowException(LogThreadID, ex, logMsg);
            }
            return true;
        }

        override public string NextStep()
        {
            return null;
        }

        private bool ChangedOrgType(int regId)
        {
            // generated by sp_Admin_StoredProcBuilder on Apr 14 2014 10:45AM
            // create parameters objects and fill with values
            List<SqlParameter> parameters = new List<SqlParameter>();

            parameters.Add(SqlParms.CreateParameter("REG_ID", DbType.Int32, regId, true));

            // verify if the payment information has changed
            return Methods.GetBoolean(DataAccess.ExecuteScalar("usp_ValidateOrganizationType", parameters));
        }

        private string SelectMedicaidId(int serviceLocationID)
        {
            string returnVal = string.Empty;
            string logProcessName = String.Format(Constants.LogString.MethodSignature, MethodBase.GetCurrentMethod().DeclaringType.Name
                , MethodBase.GetCurrentMethod().Name);

            try
            {
                // generated by sp_Admin_StoredProcBuilder on Nov  8 2013 11:35AM
                // create parameters objects and fill with values
                List<SqlParameter> parameters = new List<SqlParameter>();

                parameters.Add(SqlParms.CreateParameter("ServiceLocationID", DbType.Int32, serviceLocationID, true));

                DataSet ds = DataAccess.ExecuteStoredProcedure("usp_SelectServiceLocationById", parameters, "ServiceLocations");

                // loop over records in dataset
                foreach (DataRow location in ds.Tables[0].Rows)
                {
                    returnVal = ObjectControllerHelper.GetString("MedicaidID", location);
                }
            }
            catch (Exception ex)
            {
                CoreException.ThrowException(LogThreadID, ex, logProcessName);
            }
            return returnVal;
        }
    }
