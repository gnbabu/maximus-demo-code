using MAXIMUS.Core.Libraries;
using System;
using System.Collections.Generic;
using System.Data;
using System.Data.SqlClient;
using System.Reflection;
using Workflow;
using CON = MAXIMUS.Core.Libraries.Constants;

namespace PDMSWorkflow
{
    public class WFReceiveOrganizationID : BaseWorkflowTask, IWorkflowTask
    {
        string nextStep = null;

        public WFReceiveOrganizationID(int processID, int stepID)
            : base(processID, stepID)
        {
        }

        override public bool ProcessTask()
        {
            string logMsg = String.Format(Constants.LogString.MethodSignature, MethodBase.GetCurrentMethod().DeclaringType.Name, MethodBase.GetCurrentMethod().Name);
            Logging log = new Logging(LogThreadID, logMsg);

            bool toReturn = false;

            string partyID = GetProcessParameter(CON.ProcessParameter.PartyID);
            string serviceLocationID = GetProcessParameter(CON.ProcessParameter.ServiceLocationID);
            string tqId = GetProcessParameter(CON.ProcessParameter.TransactionQueueID);
            int hasId = 0;

            try
            {
                if (tqId.Length == 0 || tqId == "-1") { tqId = "0"; }

                // verify if medicaid ids have been received for party based on processed transactions
                // generated by sp_Admin_StoredProcBuilder on Oct 18 2013  1:34PM
                // create parameters objects and fill with values
                List<SqlParameter> parameters = new List<SqlParameter>();

                parameters.Add(SqlParms.CreateParameter("PARTY_ID", DbType.Int32, partyID, true));
                parameters.Add(SqlParms.CreateParameter("MEDICAID_PK", DbType.Int32, serviceLocationID, true));
                parameters.Add(SqlParms.CreateParameter("TRANSACTION_QUEUE_ID", DbType.Int32, tqId, true));

                hasId = Methods.GetIntValue(DataAccess.ExecuteScalar("usp_ValidateMedicaidIds", parameters));

                if (hasId == (int)Constants.MMISStatusType.Processed)
                {
                    toReturn = true;
                    nextStep = "Next";
                }
                else if (hasId == (int)Constants.MMISStatusType.Errors)
                {
                    toReturn = true;
                    nextStep = "Error";
                }
            }
            catch (Exception ex)
            {
                if (System.Diagnostics.Debugger.IsAttached) System.Diagnostics.Debugger.Break();
                throw CoreException.ThrowException(LogThreadID, ex, logMsg);
            }
            return toReturn;
        }
        override public string NextStep()
        {
            return nextStep;
        }
    }
}
